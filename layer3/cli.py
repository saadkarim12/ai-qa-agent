"""Layer 3 demo CLI.

    python3 -m layer3 sample_data/qa/18_stories.pdf
    python3 -m layer3 doc.pdf --budget 15 --json plan.json
"""

import argparse
import json
import sys
from typing import List

from layer3.contracts import TestPlan
from layer3.pipeline import plan_from_document_and_app

_R, _D, _B = "\033[0m", "\033[2m", "\033[1m"
_PRI = {"P1": "\033[91m", "P2": "\033[93m", "P3": "\033[96m", "P4": "\033[90m"}


def _c(t, colour, on):
    return f"{colour}{t}{_R}" if on else t


def render(plan: TestPlan, colour: bool) -> str:
    out: List[str] = []
    add = out.append
    s = plan.stats
    st = plan.strategy

    add("")
    add(_c("Layer 3 - Test Intelligence", _B, colour))
    add(_c("  " + st.scope_summary, _D, colour))
    add("")

    add(_c("TEST STRATEGY", _B, colour))
    add("  workflows  : " + ", ".join(st.workflows_in_scope))
    add("  scoring    : " + st.scoring_formula)
    add(_c("  not scored : " + "; ".join(st.unavailable_signals), _D, colour))
    add("")

    add(_c("COVERAGE", _B, colour))
    c = plan.coverage
    add("  %s%% of requirements covered (%d/%d)   confirmed %d / inferred %d"
        % (c.coverage_pct, c.requirements_covered, c.requirements_total,
           c.confirmed_requirements, c.inferred_requirements))
    for w in c.by_workflow:
        add("    %-38s %2d reqs  %2d tests  %5.1f%%"
            % (w.workflow[:38], w.requirements, w.tests, w.coverage_pct))
    if c.unclear_refs:
        add(_c("  needs clarification: " + ", ".join(c.unclear_refs), "\033[33m", colour))
    add("")

    add(_c("PRIORITISED EXECUTION PLAN", _B, colour))
    p = plan.execution_plan
    add("  run %d of %d tests in ~%s min%s"
        % (p.selected_tests, p.total_tests, s["estimated_minutes"],
           ("  (budget %d min)" % p.budget_minutes) if p.budget_minutes else ""))
    add("")
    add(_c("   #  score  pri  cum    test", _D, colour))
    for r in p.order:
        mark = "" if r.selected else _c("  [deferred]", _D, colour)
        add("  %2d  %5.1f  %s  %4dm  %s%s"
            % (r.rank, r.score, _c(r.priority.value, _PRI.get(r.priority.value, ""), colour),
               round(r.cumulative_seconds / 60), r.title[:56], mark))
    add("")

    add(_c("TEST CASES", _B, colour))
    for t in plan.test_cases:
        head = "  %s  %s  %s  score %.1f" % (
            _c(t.id, _B, colour), t.category.value,
            _c(t.priority.value, _PRI.get(t.priority.value, ""), colour), t.score)
        add(head)
        add("    " + t.title)
        add(_c("    why: " + " + ".join("%s %.1f" % (k, v) for k, v in t.score_breakdown.items()),
               _D, colour))
        for step in t.steps:
            line = "      %d. %s" % (step.index, step.action)
            if step.locator:
                line += _c("   [%s]" % step.locator, _D, colour)
            if step.expected:
                line += _c("  => " + step.expected, _D, colour)
            add(line)
        add("    expected: " + t.expected_result)
        if t.page_path:
            add(_c("    page: %s  [%s]" % (t.page_path, t.binding), _D, colour))
        add(_c("    traces to: " + ", ".join(t.requirement_refs), _D, colour))
        if t.needs_clarification:
            for q in t.clarification_reasons:
                add(_c("    ? " + q, "\033[33m", colour))
        add("")

    add(_c("TEST DATA REQUIREMENTS", _B, colour))
    for d in plan.test_data:
        add("  %-26s %s" % (d.id, d.name))
        add(_c("      %s" % d.description, _D, colour))
        add(_c("      fields: %s  |  %s  |  used by %d test(s)"
               % (", ".join(d.fields), d.sensitivity, len(d.used_by)), _D, colour))
    add("")

    add(_c("-" * 74, _D, colour))
    add("%d tests   %s   coverage %s%%   ~%s min"
        % (s["total"], " ".join("%s %d" % kv for kv in sorted(s["by_priority"].items())),
           s["coverage_pct"], s["estimated_minutes"]))
    add(_c("generated by: %s (no model calls)" % plan.generator, _D, colour))

    if plan.warnings:
        add("")
        add(_c("Warnings", _B, colour))
        for w in plan.warnings:
            add(_c("  ! " + w, "\033[33m", colour))
    add("")
    add(_c("Limitations", _B, colour))
    for l in st.limitations:
        add(_c("  - " + l, _D, colour))
    add("")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="layer3", description="Layer 3 - build a test plan from a requirements document.")
    ap.add_argument("document", nargs="?", default=None,
                    help="Requirements document (optional if --url is given)")
    ap.add_argument("--url", help="Application to discover with Layer 2 and bind tests to")
    ap.add_argument("--user", help="Username for the application under test")
    ap.add_argument("--password", help="Password for the application under test")
    ap.add_argument("--probe", action="append", default=None, metavar="PATH",
                    help="Extra path for discovery to try, e.g. --probe /admin")
    ap.add_argument("--budget", type=int, default=None, metavar="MIN",
                    help="Run budget in minutes; lower-ranked tests are deferred")
    ap.add_argument("--json", dest="json_out", metavar="PATH")
    ap.add_argument("--llm", action="store_true", default=False,
                    help="Allow Layer 1 LLM enrichment (off by default)")
    ap.add_argument("--no-colour", dest="colour", action="store_false", default=True)
    a = ap.parse_args(argv)

    if not a.document and not a.url:
        print("error: supply a document, a --url, or both", file=sys.stderr)
        return 2

    try:
        plan, _ = plan_from_document_and_app(
            path=a.document, url=a.url, username=a.user, password=a.password,
            budget_minutes=a.budget, use_llm=a.llm, probe_paths=a.probe)
    except (FileNotFoundError, ValueError) as exc:
        print("error: %s" % exc, file=sys.stderr)
        return 2

    print(render(plan, a.colour and sys.stdout.isatty()))
    if a.json_out:
        with open(a.json_out, "w", encoding="utf-8") as fh:
            json.dump(plan.model_dump(mode="json"), fh, indent=2)
        print("wrote test plan to %s" % a.json_out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
