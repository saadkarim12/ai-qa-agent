def to_docx(plan: TestPlan, app_map=None, generated: Optional[str] = None) -> bytes:
    import docx
    from docx.shared import Pt

    st = plan.strategy
    c = plan.coverage
    d = docx.Document()

    d.add_heading("QA Test Plan — %s" % st.document_name, level=0)
    meta = d.add_paragraph("Generated %s by AI QA Agent (Layers 1–3)."
                           % (generated or _today()))
    meta.runs[0].font.size = Pt(9)

    d.add_heading("1. Summary", level=1)
    rows = _summary_rows(plan, app_map)
    table = d.add_table(rows=len(rows), cols=2)
    table.style = "Light Grid Accent 1"
    for i, (k, v) in enumerate(rows):
        table.rows[i].cells[0].text = k
        table.rows[i].cells[1].text = v

    d.add_heading("2. Scope and approach", level=1)
    d.add_paragraph(st.scope_summary)
    d.add_paragraph("Workflows in scope: " + ", ".join(st.workflows_in_scope))
    d.add_paragraph(st.risk_approach)
    d.add_paragraph(st.scoring_formula)
    d.add_paragraph("Signals not yet available, scored as zero:")
    for u in st.unavailable_signals:
        d.add_paragraph(u, style="List Bullet")

    n = 3
    if app_map is not None:
        d.add_heading("3. Application discovered", level=1)
        pages = d.add_table(rows=1, cols=4)
        pages.style = "Light Grid Accent 1"
        for i, h in enumerate(("Page", "Status", "Forms", "Notes")):
            pages.rows[0].cells[i].text = h
        for p in app_map.pages:
            cells = pages.add_row().cells
            cells[0].text = p.path
            cells[1].text = str(p.status)
            cells[2].text = str(len(p.forms))
            cells[3].text = ("access denied" if p.access_denied
                             else ("sign-in required" if p.requires_auth else ""))
        if app_map.blocked_actions:
            d.add_heading("Actions the crawler refused to perform", level=2)
            d.add_paragraph(
                "These were identified as destructive and were never triggered. They "
                "still need testing — deliberately, by a person who understands the "
                "consequences.")
            for b in app_map.blocked_actions:
                d.add_paragraph(b, style="List Bullet")
        n = 4

    d.add_heading("%d. Coverage" % n, level=1)
    cov = d.add_table(rows=1, cols=4)
    cov.style = "Light Grid Accent 1"
    for i, h in enumerate(("Workflow", "Requirements", "Tests", "Covered")):
        cov.rows[0].cells[i].text = h
    for w in c.by_workflow:
        cells = cov.add_row().cells
        cells[0].text = w.workflow
        cells[1].text = str(w.requirements)
        cells[2].text = str(w.tests)
        cells[3].text = "%.1f%%" % w.coverage_pct
    if c.unclear_refs:
        d.add_paragraph("Not testable as written — these need clarification:")
        for r in c.unclear_refs:
            d.add_paragraph(r, style="List Bullet")

    d.add_heading("%d. Prioritised execution plan" % (n + 1), level=1)
    plan_t = d.add_table(rows=1, cols=5)
    plan_t.style = "Light Grid Accent 1"
    for i, h in enumerate(("#", "Score", "Priority", "Test", "Cumulative")):
        plan_t.rows[0].cells[i].text = h
    for r in plan.execution_plan.order:
        cells = plan_t.add_row().cells
        cells[0].text = str(r.rank)
        cells[1].text = "%.1f" % r.score
        cells[2].text = r.priority.value
        cells[3].text = r.title + ("" if r.selected else "  (deferred)")
        cells[4].text = "%dm" % round(r.cumulative_seconds / 60)

    d.add_heading("%d. Test cases" % (n + 2), level=1)
    for t in plan.test_cases:
        d.add_heading("%s — %s" % (t.id, t.title), level=2)
        d.add_paragraph("Priority %s (score %.1f)  |  Risk %s  |  Type %s"
                        % (t.priority.value, t.score, t.risk.value, t.category.value))
        d.add_paragraph("Actor: %s  |  Workflow: %s" % (t.actor, t.workflow))
        if t.page_path:
            d.add_paragraph("Page: %s (%s)" % (t.page_path, t.binding))
        d.add_paragraph("Why this rank: "
                        + " + ".join("%s %.1f" % kv for kv in t.score_breakdown.items()))
        if t.preconditions:
            d.add_paragraph("Preconditions: " + "; ".join(t.preconditions))
        for s in t.steps:
            line = s.action
            if s.locator:
                line += "   [%s]" % s.locator
            if s.expected:
                line += "  =>  " + s.expected
            d.add_paragraph(line, style="List Number")
        d.add_paragraph("Expected result: " + t.expected_result)
        d.add_paragraph("Traces to: " + ", ".join(t.requirement_refs))
        if t.needs_clarification and t.clarification_reasons:
            d.add_paragraph("Questions that must be answered first:")
            for q in t.clarification_reasons:
                d.add_paragraph(q, style="List Bullet")

    d.add_heading("%d. Test data required" % (n + 3), level=1)
    for td in plan.test_data:
        d.add_heading("%s — %s" % (td.id, td.name), level=2)
        d.add_paragraph(td.description)
        d.add_paragraph("Fields: " + ", ".join(td.fields))
        d.add_paragraph("Handling: %s   |   Used by %d test(s)"
                        % (td.sensitivity, len(td.used_by)))

    d.add_heading("%d. Assumptions, exclusions and limitations" % (n + 4), level=1)
    for title, items in (("Assumptions", st.assumptions),
                         ("Out of scope", st.exclusions),
                         ("Limitations", st.limitations),
                         ("Entry criteria", st.entry_criteria),
                         ("Exit criteria", st.exit_criteria)):
        if not items:
            continue
        d.add_heading(title, level=2)
        for i in items:
            d.add_paragraph(i, style="List Bullet")

    if plan.warnings:
        d.add_heading("%d. Warnings from this run" % (n + 5), level=1)
        for w in plan.warnings:
            d.add_paragraph(w, style="List Bullet")

    buffer = io.BytesIO()
    d.save(buffer)
    return buffer.getvalue()
