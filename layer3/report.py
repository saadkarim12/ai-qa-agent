def to_html(plan: TestPlan, app_map=None, generated: Optional[str] = None,
            title: Optional[str] = None) -> str:
    """Markdown rendered to a standalone, theme-aware page that prints to PDF."""
    md = to_markdown(plan, app_map, generated)
    body: List[str] = []
    in_table = in_list = in_code = False

    def close_blocks():
        nonlocal in_table, in_list
        if in_table:
            body.append("</table></div>")
            in_table = False
        if in_list:
            body.append("</ul>")
            in_list = False

    def inline(text: str) -> str:
        text = html.escape(text)
        for marker, tag in (("**", "strong"), ("_", "em")):
            parts = text.split(marker)
            if len(parts) > 2:
                out, open_tag = [], False
                for i, p in enumerate(parts):
                    out.append(p)
                    if i < len(parts) - 1:
                        out.append("<%s%s>" % ("" if not open_tag else "/", tag))
                        open_tag = not open_tag
                text = "".join(out)
        text = text.replace("&amp;nbsp;", "&nbsp;")
        while "`" in text:
            a = text.find("`")
            b = text.find("`", a + 1)
            if b == -1:
                break
            text = text[:a] + "<code>" + text[a + 1:b] + "</code>" + text[b + 1:]
        return text

    open_case = [False]
    summary_open = [False]

    def close_case():
        if open_case[0]:
            body.append("</div>")
            open_case[0] = False

    for line in md.splitlines():
        if line.startswith("```"):
            close_blocks()
            body.append("</pre>" if in_code else "<pre>")
            in_code = not in_code
            continue
        if in_code:
            body.append(html.escape(line))
            continue
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(set(c) <= set("-: ") for c in cells):
                continue
            if not in_table:
                body.append('<div class="tablewrap%s"><table>'
                            % (" summary" if summary_open[0] else ""))
                summary_open[0] = False
                in_table = True
                body.append("<tr>%s</tr>" % "".join("<th>%s</th>" % inline(c) for c in cells))
                continue
            body.append("<tr>%s</tr>" % "".join("<td>%s</td>" % inline(c) for c in cells))
            continue
        close_blocks() if not line.startswith(("-", "1.", "2.", "3.", "4.", "5.",
                                               "6.", "7.", "8.", "9.")) else None
        if line.startswith("### "):
            close_blocks()
            close_case()
            heading = line[4:]
            pri = _priority_of(heading, plan)
            if pri:
                body.append('<div class="case %s"><h3>%s<span class="pill %s">%s</span></h3>'
                            % (pri, inline(heading), pri, pri))
                open_case[0] = True
            else:
                body.append("<h3>%s</h3>" % inline(heading))
        elif line.startswith("## "):
            close_blocks(); close_case()
            section = inline(line[3:])
            body.append("<h2>%s</h2>" % section)
            if line[3:].strip().endswith("Summary"):
                summary_open[0] = True
        elif line.startswith("# "):
            close_blocks(); body.append("<h1>%s</h1>" % inline(line[2:]))
        elif line.startswith("- "):
            if not in_list:
                body.append("<ul>"); in_list = True
            body.append("<li>%s</li>" % inline(line[2:]))
        elif line[:2].isdigit() or (line[:1].isdigit() and line[1:2] == "."):
            body.append("<div>%s</div>" % inline(line))
        elif line.strip():
            body.append("<p>%s</p>" % inline(line))
    close_blocks()
    close_case()

    name = title or ("Test Plan — %s" % plan.strategy.document_name)
    stats = plan.stats
    masthead = (
        '<header class="masthead">'
        '<div class="eyebrow">AI QA Agent · Layers 1–3</div>'
        '<h1>%s</h1>'
        '<div class="byline">%s &nbsp;·&nbsp; %d test cases &nbsp;·&nbsp; %.1f%% requirement '
        'coverage &nbsp;·&nbsp; generated by deterministic rules, no AI model calls</div>'
        '</header>'
        % (html.escape(name), html.escape(generated or _today()),
           stats["total"], plan.coverage.coverage_pct)
    )
    # The generated H1 duplicates the masthead; drop it.
    rendered = "\n".join(body)
    if rendered.startswith("<h1>"):
        rendered = rendered[rendered.index("</h1>") + 5:]

    return (
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
        "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
        "<title>%s</title>%s<style>%s</style></head>"
        "<body><div class=\"wrap\">%s%s</div></body></html>"
        % (html.escape(name), _HTML_HEAD, _HTML_CSS, masthead, rendered)
    )


