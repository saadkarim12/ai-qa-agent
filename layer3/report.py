"""Deliverable report generation.

The layers produce structured objects; a customer wants a document. This turns
a TestPlan (plus, optionally, the Application Map behind it) into something a
person can read, circulate and sign off:

    Markdown  - for a repo or a wiki
    HTML      - opens in any browser, prints to PDF
    DOCX      - for the Word-shaped world most QA teams actually live in

Every number in here comes from the plan. Nothing is recomputed, softened or
rounded up on the way out.
"""

import datetime
import html
import io
from typing import List, Optional

from layer3.contracts import TestPlan


def _summary_rows(plan: TestPlan, app_map=None) -> List[tuple]:
    s = plan.stats
    c = plan.coverage
    rows = [
        ("Test cases", str(s["total"])),
        ("Priority split", "  ".join("%s %d" % kv for kv in sorted(s["by_priority"].items()))),
        ("Requirement coverage", "%.1f%% (%d of %d)"
         % (c.coverage_pct, c.requirements_covered, c.requirements_total)),
        ("Customer-confirmed requirements", str(c.confirmed_requirements)),
        ("Inferred from the application", str(c.inferred_requirements)),
        ("Needing clarification", str(s["needs_clarification"])),
        ("Selected for this run", "%d of %d (~%s minutes)"
         % (plan.execution_plan.selected_tests, plan.execution_plan.total_tests,
            s["estimated_minutes"])),
        ("Generated by", "%s - deterministic rules, no AI model calls" % plan.generator),
    ]
    if app_map is not None:
        st = app_map.stats
        rows.insert(3, ("Pages discovered", str(st["pages"])))
        rows.insert(4, ("Destructive actions blocked", str(st["blocked_actions"])))
    return rows


# ---------------------------------------------------------------- markdown

def to_markdown(plan: TestPlan, app_map=None, generated: Optional[str] = None) -> str:
    st = plan.strategy
    c = plan.coverage
    out: List[str] = []
    a = out.append

    a("# QA Test Plan — %s" % st.document_name)
    a("")
    a("Generated %s by AI QA Agent (Layers 1–3)." % (generated or _today()))
    a("")

    a("## 1. Summary")
    a("")
    a("| | |")
    a("|---|---|")
    for k, v in _summary_rows(plan, app_map):
        a("| %s | %s |" % (k, v))
    a("")

    a("## 2. Scope and approach")
    a("")
    a(st.scope_summary)
    a("")
    a("**Workflows in scope:** %s" % ", ".join(st.workflows_in_scope))
    a("")
    a("**How tests are prioritised.** %s" % st.risk_approach)
    a("")
    a("```")
    a(st.scoring_formula)
    a("```")
    a("")
    a("Signals not yet available, and therefore scored as zero:")
    a("")
    for u in st.unavailable_signals:
        a("- %s" % u)
    a("")

    if app_map is not None:
        a("## 3. Application discovered")
        a("")
        a("| Page | Status | Forms | Notes |")
        a("|---|---|---|---|")
        for p in app_map.pages:
            note = "access denied" if p.access_denied else (
                "sign-in required" if p.requires_auth else "")
            a("| `%s` | %s | %d | %s |" % (p.path, p.status, len(p.forms), note))
        a("")
        if app_map.blocked_actions:
            a("### Actions the crawler refused to perform")
            a("")
            a("These were identified as destructive and were never triggered. "
              "They still need testing — deliberately, by a person who understands "
              "the consequences.")
            a("")
            for b in app_map.blocked_actions:
                a("- %s" % b)
            a("")

    n = 4 if app_map is not None else 3
    a("## %d. Coverage" % n)
    a("")
    a("| Workflow | Requirements | Tests | Covered |")
    a("|---|---|---|---|")
    for w in c.by_workflow:
        a("| %s | %d | %d | %.1f%% |" % (w.workflow, w.requirements, w.tests, w.coverage_pct))
    a("")
    if c.unclear_refs:
        a("**Not testable as written** — these need clarification before a test can exist:")
        a("")
        for r in c.unclear_refs:
            a("- `%s`" % r)
        a("")

    a("## %d. Prioritised execution plan" % (n + 1))
    a("")
    a("| # | Score | Priority | Test | Cumulative |")
    a("|---|---|---|---|---|")
    for r in plan.execution_plan.order:
        a("| %d | %.1f | %s | %s%s | %dm |"
          % (r.rank, r.score, r.priority.value, r.title,
             "" if r.selected else " _(deferred)_", round(r.cumulative_seconds / 60)))
    a("")

    a("## %d. Test cases" % (n + 2))
    a("")
    for t in plan.test_cases:
        a("### %s — %s" % (t.id, t.title))
        a("")
        a("- **Priority:** %s (score %.1f) &nbsp;|&nbsp; **Risk:** %s &nbsp;|&nbsp; "
          "**Type:** %s" % (t.priority.value, t.score, t.risk.value, t.category.value))
        a("- **Actor:** %s &nbsp;|&nbsp; **Workflow:** %s" % (t.actor, t.workflow))
        if t.page_path:
            a("- **Page:** `%s` (%s)" % (t.page_path, t.binding))
        a("- **Why this rank:** %s"
          % " + ".join("%s %.1f" % kv for kv in t.score_breakdown.items()))
        a("")
        if t.preconditions:
            a("**Preconditions:** %s" % "; ".join(t.preconditions))
            a("")
        a("**Steps**")
        a("")
        for s in t.steps:
            line = "%d. %s" % (s.index, s.action)
            if s.locator:
                line += "  `%s`" % s.locator
            if s.expected:
                line += " → _%s_" % s.expected
            a(line)
        a("")
        a("**Expected result:** %s" % t.expected_result)
        a("")
        a("**Traces to:** %s" % ", ".join("`%s`" % r for r in t.requirement_refs))
        a("")
        if t.needs_clarification and t.clarification_reasons:
            a("**Questions that must be answered first:**")
            a("")
            for q in t.clarification_reasons:
                a("- %s" % q)
            a("")

    a("## %d. Test data required" % (n + 3))
    a("")
    for d in plan.test_data:
        a("**%s — %s**" % (d.id, d.name))
        a("")
        a("%s" % d.description)
        a("")
        a("- Fields: %s" % ", ".join(d.fields))
        a("- Handling: %s" % d.sensitivity)
        a("- Used by %d test(s)" % len(d.used_by))
        a("")

    a("## %d. Assumptions, exclusions and limitations" % (n + 4))
    a("")
    for title, items in (("Assumptions", st.assumptions),
                         ("Out of scope", st.exclusions),
                         ("Limitations", st.limitations),
                         ("Entry criteria", st.entry_criteria),
                         ("Exit criteria", st.exit_criteria)):
        if not items:
            continue
        a("**%s**" % title)
        a("")
        for i in items:
            a("- %s" % i)
        a("")

    if plan.warnings:
        a("## %d. Warnings from this run" % (n + 5))
        a("")
        for w in plan.warnings:
            a("- %s" % w)
        a("")

    return "\n".join(out)


def _priority_of(heading: str, plan: TestPlan) -> Optional[str]:
    """Match a '### TC-007 — ...' heading back to its test, for the severity stripe."""
    tid = heading.split(" ", 1)[0].strip()
    for t in plan.test_cases:
        if t.id == tid:
            return t.priority.value
    return None


def _today() -> str:
    return datetime.datetime.now().strftime("%d %B %Y, %H:%M")


